    public static readonly byte[] GfLog = new byte[256];

    /// <summary>
    /// 静态构造初始化 GF(256) 表。对应 JS IIFE 中填充 <c>Gt</c>/<c>Kt</c> 的逻辑。
    /// </summary>
    static QrTables()
    {
        var x = 1;
        for (var i = 0; i < 255; i++)
        {
            GfExp[i] = (byte)x;
            GfLog[x] = (byte)i;
            x <<= 1;
            if ((x & 256) != 0) x ^= 285;
        }
        // 255-511 镜像
        for (var i = 255; i < 512; i++)
            GfExp[i] = GfExp[i - 255];
    }
